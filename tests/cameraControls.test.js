import assert from 'node:assert/strict';
import { EventEmitter } from 'node:events';
import { CameraControls } from '../src/input/CameraControls.js';
import { syncViewportSize } from '../src/input/ResponsiveViewport.js';

const input = new EventEmitter();
input.keyboard = new EventEmitter();
const events = new EventEmitter();
const camera = { zoom: 1, setZoom(value) { this.zoom = value; } };
const scale = new EventEmitter();
scale.width = 960; scale.height = 540;
const scene = { input, events, scale, cameras: { main: camera }, inputRouter: { isFrozen: false } };
const controls = new CameraControls(scene);
const key = (code, extra = {}) => input.keyboard.emit('keydown', { code, preventDefault() {}, ...extra });

input.emit('wheel', {}, [], 0, -100, 0);
assert.ok(controls.targetZoom > 1, 'scroll up zooms in');
controls.update(100);
assert.ok(camera.zoom > 1 && camera.zoom < controls.targetZoom, 'zoom approaches its target smoothly');
input.emit('wheel', {}, [], 0, 200, 0);
assert.ok(controls.targetZoom < 1, 'scroll down zooms out');
key('Digit0');
assert.equal(controls.targetZoom, 1, 'zero restores default zoom');
key('Equal');
assert.ok(controls.targetZoom > 1, 'plus zooms in');
key('NumpadSubtract');
assert.equal(controls.targetZoom, 1, 'numpad minus zooms out');
for (let i = 0; i < 100; i++) key('Minus');
assert.equal(controls.targetZoom, 0.5, 'zoom out has a lower limit');
for (let i = 0; i < 100; i++) key('NumpadAdd');
assert.equal(controls.targetZoom, 1.75, 'zoom in has an upper limit');
key('Digit0');
scene.inputRouter.isFrozen = true;
key('Equal');
input.emit('wheel', {}, [], 0, -100, 0);
assert.equal(controls.targetZoom, 1, 'menus and dialogue block camera input');
scene.inputRouter.isFrozen = false;
key('Equal', { ctrlKey: true });
assert.equal(controls.targetZoom, 1, 'browser shortcuts are left alone');
scale.emit('resize', { width: 390, height: 844 });
assert.equal(camera.zoom, 0.9, 'portrait viewport keeps usable world scale without a letterboxed strip');
scale.emit('resize', { width: 1920, height: 1080 });
assert.equal(camera.zoom, 1.6, 'returning to desktop restores the desktop camera scale');
assert.equal(controls.targetZoom, 1, 'viewport changes preserve user zoom preference');
events.emit('shutdown');
assert.equal(input.listenerCount('wheel'), 0, 'wheel listener removed at scene shutdown');
assert.equal(input.keyboard.listenerCount('keydown'), 0, 'keyboard listener removed at scene shutdown');
assert.equal(scale.listenerCount('resize'), 0, 'responsive camera listener is cleaned up');
const viewportGame = { scale: { width: 390, height: 844, setParentSize(width, height) { this.width = width; this.height = height; } } };
const parent = { getBoundingClientRect: () => ({ width: 844, height: 390 }) };
assert.equal(syncViewportSize(viewportGame, parent), true);
assert.equal(viewportGame.scale.width, 844, 'orientation change resizes the actual canvas parent');
assert.equal(syncViewportSize(viewportGame, parent), false, 'identical sizes do not reallocate the canvas');
console.log('Camera controls: wheel, keyboard, smoothing, limits, pause and cleanup PASS');
